create or replace function public.set_post_timestamps()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
  new.updated_at = now();

  if new.status = 'published'
     and (old.status is distinct from 'published' or new.published_at is null) then
    new.published_at = now();
  elsif new.status = 'draft' then
    new.published_at = null;
  end if;

  return new;
end;
$$;

create or replace function public.trim_post_revisions()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  delete from public.post_revisions
  where post_id = new.post_id
    and id not in (
      select id
      from public.post_revisions
      where post_id = new.post_id
      order by created_at desc
      limit 20
    );
  return new;
end;
$$;

drop trigger if exists trg_trim_post_revisions on public.post_revisions;
create trigger trg_trim_post_revisions
  after insert on public.post_revisions
  for each row execute function public.trim_post_revisions();

create or replace function public.publish_scheduled_posts()
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  published_count integer;
begin
  update public.posts
  set status = 'published'
  where status = 'scheduled'
    and published_at is not null
    and published_at <= now();

  get diagnostics published_count = row_count;
  return published_count;
end;
$$;

create or replace function public.track_post_view(target_post_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.post_views (post_id) values (target_post_id);
  update public.posts
  set view_count = view_count + 1
  where id = target_post_id and status = 'published';
end;
$$;

create or replace function public.track_affiliate_click(target_link_id uuid)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  target_url text;
begin
  select destination_url into target_url
  from public.affiliate_links
  where id = target_link_id and active = true;

  if target_url is null then
    return null;
  end if;

  insert into public.affiliate_clicks (affiliate_link_id)
  values (target_link_id);

  update public.affiliate_links
  set click_count = click_count + 1, updated_at = now()
  where id = target_link_id;

  return target_url;
end;
$$;

revoke all on function public.publish_scheduled_posts() from public;
grant execute on function public.publish_scheduled_posts() to authenticated, service_role;
grant execute on function public.track_post_view(uuid) to anon, authenticated;
grant execute on function public.track_affiliate_click(uuid) to anon, authenticated;

