create index if not exists idx_post_revisions_post_created
  on public.post_revisions(post_id, created_at desc);
create index if not exists idx_affiliate_links_post on public.affiliate_links(post_id);
create index if not exists idx_affiliate_clicks_date
  on public.affiliate_clicks(clicked_at desc);
create index if not exists idx_post_views_date
  on public.post_views(viewed_at desc);
create index if not exists idx_post_views_post_date
  on public.post_views(post_id, viewed_at desc);
